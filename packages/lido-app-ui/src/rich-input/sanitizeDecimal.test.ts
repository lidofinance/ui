import { describe, expect, it } from 'vitest'

import { sanitizeDecimal } from './sanitizeDecimal'

describe('sanitizeDecimal', () => {
  it.each([
    ['1,234.56', 8, '1234.56', 7],
    ['1.000,50', 8, '1000.50', 7],
    ['1,000', 5, '1000', 4],
    ['1.234,56', 8, '1234.56', 7],
    ['1 234,56', 8, '1234.56', 7],
    ['.5', 2, '.5', 2],
    ['0,', 2, '0.', 2],
    ['1a2b', 1, '12', 1],
    ['1,5x', 1, '1.5', 1],
    ['1,234,567', 9, '1234567', 7],
    ['1.234.567', 9, '1234567', 7],
    ['1,5', 3, '1.5', 3],
    ['0,123', 5, '0.123', 5],
    ['12,34', 5, '12.34', 5],
    ['1.234', 5, '1.234', 5],
    ['1.5,', 4, '1.5', 3],
    ['1.5.', 4, '1.5', 3],
    ['$1,234.56 ETH', 13, '1234.56', 7],
    ['.1.5', 1, '.15', 1],
    ['1a2', 2, '12', 1],
    ['12a', 1, '12', 1],
    [',5', 2, '.5', 2],
    ['', 0, '', 0],
    ['1234', null, '1234', null],
    ['1,234.', 6, '1234.', 5],
    ['1.234,', 6, '1.234', 5],
    ['1.000,', 6, '1.000', 5],
  ] as const)(
    '%j with caret %j -> %j, caret %j',
    (raw, caretIn, value, caret) => {
      expect(sanitizeDecimal(raw, caretIn)).toEqual({ value, caret })
    },
  )

  it.each([
    ['1.239', 2, 5, '1.23', 4],
    ['1.2934', 3, 4, '1.293', 4],
    ['1,234.5678', 2, 10, '1234.56', 7],
    ['1.5', 0, 3, '1', 1],
    ['12.', 0, 3, '12', 2],
    ['1.23', undefined, 4, '1.23', 4],
    ['.123', 1, 4, '.1', 2],
    ['1.000', 0, 2, '1000', 1],
    ['1.2345', 2, 2, '12345', 1],
    ['1.2.50', 2, 2, '12.50', 1],
    ['1,2,50', 2, 2, '12.50', 1],
  ] as const)(
    '%j capped to %j decimals with caret %j -> %j, caret %j',
    (raw, decimals, caretIn, value, caret) => {
      expect(sanitizeDecimal(raw, caretIn, decimals)).toEqual({ value, caret })
    },
  )
})
